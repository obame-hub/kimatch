-- RÉTABLIR LE LIEN CONTRAT → RECOMMANDATION, PERDU À LA REPRISE SALESFORCE
--
-- Constat du 27/08/2026 : sur 1 598 contrats, TROIS portaient une recommandation. On ne pouvait donc
-- pas répondre à la question « quel contrat vient de quelle recommandation ? », qui est pourtant
-- celle qui relie le travail d'un commercial à son résultat.
--
-- ══ POURQUOI LE LIEN ÉTAIT PERDU, ET OÙ IL SE RETROUVE ══
--
-- Rien n'était cassé : le lien n'a simplement jamais été importé. Il existe côté Salesforce sous la
-- forme `Contract.Opportunit__c`. Et dans Kimatch, LA RECOMMANDATION EST L'OPPORTUNITÉ SALESFORCE :
-- les 1 599 `recommandations.id_salesforce` renseignés commencent tous par `006`, le préfixe des
-- Opportunity. La reprise a donc chargé les opportunités comme des recommandations — ce qui rend le
-- rapprochement direct, sans passer par les Cotation__c.
--
-- (C'est aussi pourquoi il n'y a rien à rétablir du côté « signal → opportunité » : la table
--  `opportunites` ne contient qu'UNE ligne, c'est un objet propre à Kimatch que la reprise n'alimente
--  pas, et `signaux` n'a même pas de colonne `id_salesforce`. Le lien `signaux.recommandation_id`,
--  déjà renseigné sur 745 signaux, EST le lien vers l'opportunité.)
--
-- ══ LES DEUX CLÉS NE SONT PAS DU MÊME TYPE, ET C'EST NORMAL ══
--
-- `contrats.id_salesforce` fait 8 caractères (`00001488`) : c'est le ContractNumber, pas un Id.
-- `recommandations.id_salesforce` fait 18 caractères : c'est l'Id de l'Opportunity.
-- Comparer les deux colonnes entre elles ne donnerait rien. Le couple ci-dessous vient de Salesforce
-- et porte les deux clés côte à côte — c'est lui qui fait le pont.
--
-- ══ CE QUE LA MIGRATION N'ÉCRIT PAS ══
--
-- Les 768 couples extraits de Salesforce donnent 694 écritures, et l'écart est voulu :
--   · les DEUX jointures sont obligatoires — un contrat absent de Kimatch ou une recommandation
--     absente ne produit aucune ligne, jamais un lien approximatif ;
--   · `recommandation_id is null` protège les 3 liens déjà en place, qu'ils viennent d'un import ou
--     d'une saisie à la main ; aucun n'est écrasé (vérifié : 0 contradiction avant écriture) ;
--   · le compte doit être le même des deux côtés. Ce garde-fou est ce qui prouve que le rapprochement
--     est le bon : sur les 694 paires, ZÉRO discordance de compte. Un numéro qui aurait collisionné
--     par hasard aurait presque sûrement désigné un autre client.
--
-- Rejouable : la clause `is null` fait de la seconde exécution une opération vide.
-- ════════════════════════════════════════════════════════════════════════════════════════════════

