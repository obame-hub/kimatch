-- La date de déclenchement de la tacite reconduction, et sa reprise depuis Salesforce.
--
-- CE QUI MANQUAIT. Salesforce porte, sur chaque contrat, la DATE LIMITE au-delà de laquelle le
-- contrat se reconduit tout seul : le champ « Déclenchement tacite ». Kimatch n'avait pas de colonne
-- pour l'accueillir. Constaté le 21/08/2026 en comparant les deux bases :
--
--   Salesforce (1 598 contrats)        Kimatch (1 599 contrats)
--   ─────────────────────────────      ────────────────────────────────
--   Tacite reconduction cochée   506   clause_tacite_reconduction vrai   233
--   Déclenchement tacite         505   — la colonne n'existe pas
--   Durée du préavis             523   preavis_resiliation_jours         523
--
-- Le préavis avait bien été repris, au contrat près. La case tacite l'a été à moitié. La date, pas
-- du tout — et c'est la seule des trois qui dise QUAND agir.
--
-- POURQUOI ON IMPORTE LA DATE AU LIEU DE LA CALCULER. On pourrait croire qu'elle vaut
-- `date_fin - préavis`. Elle n'en est pas loin, mais pas égale : RANCOUR IMMOBILIER finit le
-- 26/10/2026 avec 60 jours de préavis, le calcul donne le 27/08 et Salesforce dit le 26/08. Même
-- décalage d'un jour sur les quatre contrats suivants. Salesforce fait donc foi : on reprend SA date
-- plutôt que d'imposer une formule qu'on n'a pas écrite et dont on ne connaît pas la règle exacte.
--
-- CE QUE ÇA DÉBLOQUE. Sur les 505 dates, 482 sont encore à venir, 23 sont passées, et 13 tombent
-- dans les six prochains mois. La plus proche est RANCOUR IMMOBILIER, le 26/08/2026 — dans cinq
-- jours au moment où j'écris. Passé ce jour, le contrat court jusqu'en 2029 et il n'y a plus rien à
-- négocier. Personne dans Kimatch ne pouvait le savoir.
--
-- LA CORRESPONDANCE se fait sur `contrats.id_salesforce`, qui porte le NUMÉRO de contrat Salesforce
-- (« 00000581 ») et non son identifiant à 18 caractères. 1 485 contrats sur 1 599 en ont un, tous
-- distincts. Les 114 sans numéro sont nés dans Kimatch : ils n'ont rien à reprendre.

